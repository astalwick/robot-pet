#!/usr/bin/env python3
"""Generate urdf/robot.urdf from robot_model.py. Run from anywhere; rerun after editing robot_model.

robot_state_publisher turns this into the static base_link -> sensor TF frames
that Foxglove and slam_toolbox use. Only geometry that robot_model knows about
is here, including the lidar mount (a placeholder until it is measured).
"""

import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

from robot_model import (  # noqa: E402
    FOOTPRINT_FRONT_X_METERS,
    FOOTPRINT_HALF_WIDTH_METERS,
    FOOTPRINT_REAR_X_METERS,
    LIDAR_MOUNT,
    SENSOR_MOUNTS,
    TRACK_WIDTH_METERS,
    WHEEL_RADIUS_METERS,
)

URDF_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "urdf", "robot.urdf")
# Visual only; nothing measures the wheel width yet.
WHEEL_WIDTH_METERS = 0.03


def fixed_joint(child: str, x: float, y: float, z: float, roll: float = 0.0, pitch: float = 0.0, yaw: float = 0.0) -> str:
    return f"""  <joint name="base_to_{child}" type="fixed">
    <parent link="base_link"/>
    <child link="{child}"/>
    <origin xyz="{x:.4f} {y:.4f} {z:.4f}" rpy="{roll:.4f} {pitch:.4f} {yaw:.4f}"/>
  </joint>
"""


def wheel(name: str, y: float) -> str:
    return f"""  <link name="{name}">
    <visual>
      <origin xyz="0 0 0" rpy="{math.pi / 2:.4f} 0 0"/>
      <geometry><cylinder radius="{WHEEL_RADIUS_METERS:.4f}" length="{WHEEL_WIDTH_METERS:.4f}"/></geometry>
    </visual>
  </link>
""" + fixed_joint(name, 0.0, y, WHEEL_RADIUS_METERS)


def render_urdf() -> str:
    body_length = FOOTPRINT_FRONT_X_METERS - FOOTPRINT_REAR_X_METERS
    body_height = max(mount.z for mount in SENSOR_MOUNTS)
    parts = [
        f"""<?xml version="1.0"?>
<!-- Generated by scripts/generate-urdf.py from src/robot_model.py. Do not edit by hand. -->
<robot name="robo_pet">
  <link name="base_link">
    <visual>
      <origin xyz="{(FOOTPRINT_FRONT_X_METERS + FOOTPRINT_REAR_X_METERS) / 2:.4f} 0 {body_height / 2:.4f}" rpy="0 0 0"/>
      <geometry><box size="{body_length:.4f} {FOOTPRINT_HALF_WIDTH_METERS * 2:.4f} {body_height:.4f}"/></geometry>
    </visual>
  </link>

""",
        wheel("left_wheel", TRACK_WIDTH_METERS / 2),
        wheel("right_wheel", -TRACK_WIDTH_METERS / 2),
        "\n",
    ]
    for mount in SENSOR_MOUNTS:
        parts.append(f'  <link name="{mount.name}"/>\n')
        parts.append(fixed_joint(mount.name, mount.x, mount.y, mount.z, pitch=mount.pitch, yaw=mount.yaw))
    parts.append("""
  <!-- IMU mount is not measured yet; it sits at the base_link origin until it is. -->
  <link name="imu_link"/>
""")
    parts.append(fixed_joint("imu_link", 0.0, 0.0, 0.0))
    parts.append("""
  <!-- RPLidar A1 scan frame; the mount pose is LIDAR_MOUNT in robot_model.py -->
  <link name="laser"/>
""")
    parts.append(fixed_joint("laser", LIDAR_MOUNT.x, LIDAR_MOUNT.y, LIDAR_MOUNT.z, yaw=LIDAR_MOUNT.yaw))
    parts.append("</robot>\n")
    return "".join(parts)


def main() -> None:
    with open(URDF_PATH, "w") as handle:
        handle.write(render_urdf())
    print(f"wrote {URDF_PATH}")


if __name__ == "__main__":
    main()
